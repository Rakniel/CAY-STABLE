'use strict';
const assert=require('node:assert/strict');
const M=require('../staff_video_source_v1.js');
let checks=0;
function ok(a,b){assert.deepEqual(a,b);checks++;}
const u='https://app.veo.co/matches/20261011-example-v1234567';
const source=M.parseVeoLink(u);
ok(source.valid,true);
ok(source.url,u);
ok(source.provider,'VEO');
ok(source.status,'REFERENCE_EXTERNE');
ok(source.sourceVideoId,'veo:20261011-example-v1234567');
ok(source.analyzedByCAY,false);
ok(source.videoCoverage,null);
ok(source.evidenceStatus,'INDISPONIBLE');
ok(source.playableInAnalyzer,false);
ok(source.importRequirement,'EXPORT_MP4_AUTORISE_REQUIS');
ok(M.canBindToObservations(u,[{sourceVideoId:source.sourceVideoId}]).compatible,true);
ok(M.canBindToObservations(u,[{sourceVideoId:'old'}]).compatible,false);
ok(M.canBindToObservations(u,[{}]).compatible,true);
ok(M.parseVeoLink(u+'/other').valid,false);
ok(M.parseVeoLink('http://app.veo.co/matches/test123').valid,false);
ok(M.parseVeoLink('https://not-veo.co/matches/test123').valid,false);
ok(M.parseVeoLink('https://app.veo.co.evil.org/matches/test123').valid,false);
ok(M.parseVeoLink('javascript:alert(1)').valid,false);
ok(M.parseVeoLink('https://app.veo.co/matches/test123?token=secret').valid,false);
ok(M.parseVeoLink('https://app.veo.co/matches/test123#t=120').valid,false);
ok(M.parseVeoLink('https://x@app.veo.co/matches/test123').valid,false);
ok(M.parseVeoLink('https://app.veo.co:444/matches/test123').valid,false);
ok(M.parseVeoLink('https://app.veo.co/matches/test123').valid,true);
ok(M.parseVeoLink('https://app.veo.co/matches/test123/').valid,true);
ok(M.parseVeoLink('').reason,'VIDEO_URL_REQUIRED');
ok(M.parseVeoLink('x'.repeat(513)).reason,'VIDEO_URL_TOO_LONG');
console.log('CAY Veo source: '+checks+' assertions OK');

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const values=new Map(),previous=globalThis.localStorage;
globalThis.localStorage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,String(v))};
try{
  const Domain=require('../app_domain_models_v1.js');
  const UI=require('../club_roster_identity_ui_v1.js');
  const store=UI.createStore(globalThis.localStorage);
  const legacy=store.saveTeam({roster:[{id:'a',displayName:'Alice',status:'ACTIVE',firstName:'Alice',lastName:'Martin',secondaryPosition:'CB'},{id:'b',displayName:'B',status:'SUBSTITUTE'}],defaultLineup:[],bench:[]});
  assert.deepEqual(legacy.defaultLineup,[],'legacy lineup must never be silently changed');
  assert.deepEqual(store.team().bench,[],'legacy bench must never be silently changed');
  assert.equal(legacy.roster[0].firstName,'Alice');
  assert.equal(legacy.roster[0].secondaryPosition,'CB');
  assert.equal(legacy.roster[1].status,'SUBSTITUTE');
  assert.equal(UI.prepareLineup().accepted,true);
  assert.deepEqual(UI.currentTeam().defaultLineup,['a']);
  assert.deepEqual(UI.currentTeam().bench,['b']);
  values.clear();
  for(let i=1;i<=14;i++)assert.equal(UI.addPlayer({id:'p'+i,displayName:'Joueur '+i,number:i,primaryPosition:'CM'}).accepted,true);
  let team=UI.currentTeam();
  assert.equal(team.roster.length,14);assert.equal(team.defaultLineup.length,11);assert.equal(team.bench.length,3);
  assert.equal(Domain.validateLineup(team).valid,true);
  assert.equal(UI.setPlayerAssignment('p12','START').reason,'LINEUP_OVER_11');
  assert.equal(UI.setPlayerAssignment('p1','BENCH').accepted,true);
  assert.equal(UI.setPlayerAssignment('p12','START').accepted,true);
  assert.equal(UI.setPlayerAssignment('p14','INACTIVE').accepted,true);
  team=UI.currentTeam();
  assert.equal(team.defaultLineup.length,11);assert.equal(team.bench.length,2);
  assert.equal(team.roster.find(p=>p.id==='p14').status,'INACTIVE');
  assert.equal(store.team().roster.find(p=>p.id==='p14').status,'INACTIVE');
  assert.equal(UI.setPlayerAssignment('absent','START').reason,'UNKNOWN_ROSTER_PLAYER');
  assert.equal(UI.setPlayerAssignment('p2','INVALID').reason,'INVALID_ASSIGNMENT');
  assert.equal(UI.removePlayer('p12').removed,true);
  assert.equal(UI.currentTeam().defaultLineup.includes('p12'),false);
  values.clear();
  assert.equal(UI.addPlayer({id:'new',firstName:'Lou',lastName:'Martin',primaryPosition:'GK',secondaryPosition:'CB'}).accepted,true);
  team=UI.currentTeam();
  assert.equal(team.roster[0].displayName,'Lou Martin');
  assert.equal(team.roster[0].secondaryPosition,'CB');
  assert.equal(team.roster[0].isGoalkeeper,true);
  assert.equal(UI.setPlayerAssignment('new','INACTIVE').accepted,true);
  assert.equal(UI.currentTeam().defaultLineup.length,0);
  assert.equal(Domain.validateLineup(UI.currentTeam()).valid,false);
  const source=fs.readFileSync(require.resolve('../club_roster_identity_ui_v1.js'),'utf8');
  assert(source.includes('PRÉPARER LE 11 + BANC'));
  assert(source.includes('11 CAY maximum simultanément'));
  assert(source.includes('Aucune identité automatique'));
  assert(source.includes("confirmed:true,source:'coach_click'"));
  console.log('RUN60 roster + player profiles: PASS');
}finally{if(previous===undefined)delete globalThis.localStorage;else globalThis.localStorage=previous;}
